    <h2>1. Pengantar</h2>
    <p>Aplikasi <strong>PeopleC</strong> menghargai privasi Anda. Kebijakan privasi ini menjelaskan bagaimana kami
        mengumpulkan, menggunakan, dan melindungi informasi pribadi Anda saat menggunakan aplikasi ini.</p>
    <p>Dengan menggunakan aplikasi <strong>PeopleC</strong>, Anda menyetujui kebijakan ini.</p>

    <h2>2. Informasi yang Kami Kumpulkan</h2>
    <p>Kami dapat mengumpulkan data berikut saat Anda menggunakan aplikasi:</p>

    <h3>a. Lokasi (GPS Coordinate)</h3>
    <p>Kami mengakses lokasi Anda untuk keperluan seperti pencatatan kehadiran atau pelacakan saat menggunakan fitur
        tertentu. Data lokasi tidak dibagikan ke pihak ketiga tanpa izin Anda.</p>

    <h3>b. Kamera</h3>
    <p>Kami menggunakan kamera untuk keperluan seperti mengambil foto pengguna, memindai QR code, atau verifikasi
        identitas. Gambar hanya disimpan di perangkat atau dikirim ke server kami sesuai fitur aplikasi.</p>

    <h3>c. Penyimpanan & Foto</h3>
    <p>Kami memerlukan akses ke penyimpanan dan galeri foto Anda untuk menyimpan atau memilih gambar dari perangkat
        Anda. Kami tidak mengakses atau membagikan file Anda tanpa persetujuan Anda.</p>

    <h2>3. Bagaimana Kami Menggunakan Informasi</h2>
    <ul>
        <li>Menyediakan fitur aplikasi yang berfungsi penuh</li>
        <li>Meningkatkan kualitas layanan</li>
        <li>Melakukan pemeliharaan dan pengembangan aplikasi</li>
        <li>Menyimpan data aktivitas pengguna untuk tujuan audit (jika relevan)</li>
    </ul>

    <h2>4. Pihak Ketiga</h2>
    <p>Kami <strong>tidak menjual</strong> atau membagikan data pribadi Anda ke pihak ketiga tanpa izin. Namun, kami
        dapat menggunakan layanan pihak ketiga (misalnya Firebase, Google Maps) yang juga memiliki kebijakan privasi
        tersendiri.</p>

    <h2>5. Keamanan Data</h2>
    <p>Kami menerapkan langkah-langkah teknis dan organisasi yang wajar untuk melindungi informasi Anda dari akses yang
        tidak sah, pengubahan, pengungkapan, atau penghancuran.</p>

    <h2>6. Hak Pengguna</h2>
    <p>Anda memiliki hak untuk:</p>
    <ul>
        <li>Mengakses atau memperbarui data pribadi Anda</li>
        <li>Menarik izin akses tertentu melalui pengaturan aplikasi di perangkat Anda</li>
        <li>Menghapus akun atau data dengan menghubungi kami</li>
    </ul>

    <h2>7. Perubahan pada Kebijakan Ini</h2>
    <p>Kami dapat memperbarui kebijakan ini dari waktu ke waktu. Kami akan memberi tahu Anda jika ada perubahan
        signifikan.</p>

